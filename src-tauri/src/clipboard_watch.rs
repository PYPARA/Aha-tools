//! Watches the general pasteboard so the search panel can bring in what was just copied,
//! like uTools does. Only the kind and time of the last copy are kept here; the content
//! itself is read by the panel when it decides to use it.

use std::sync::Mutex;
use std::thread;
use std::time::{Duration, Instant};

use objc2::rc::autoreleasepool;
use objc2_app_kit::{NSPasteboard, NSWorkspace};
use serde::{Deserialize, Serialize};
use tauri::AppHandle;

#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq)]
#[serde(rename_all = "camelCase")]
pub enum ClipKind {
    Text,
    Image,
    Files,
}

/// Copies other apps mark as private (password managers) or as not worth keeping.
/// <http://nspasteboard.org>
const SKIP_TYPES: [&str; 3] = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

struct State {
    /// The pasteboard generation last seen; -1 until the first look.
    count: isize,
    /// When the last copy worth bringing in happened, and what it was.
    copied: Option<(Instant, ClipKind)>,
    /// A generation AhaTools wrote itself (copying a result, restoring after reading a
    /// selection): never brought back in.
    own: isize,
}

static STATE: Mutex<State> = Mutex::new(State { count: -1, copied: None, own: -1 });

/// A copy for 剪贴板历史 to read, noted when it happened (the app in front then).
#[derive(Clone, Debug)]
pub struct Pending {
    pub count: isize,
    pub kind: ClipKind,
    pub bundle: Option<String>,
    pub app: Option<String>,
}
static PENDING: Mutex<Vec<Pending>> = Mutex::new(Vec::new());

pub fn is_own(count: isize) -> bool {
    STATE.lock().unwrap().own == count
}

/// What the pasteboard holds, from its type list alone; None for nothing useful or private.
fn classify(types: &[String], from_ahatools: bool) -> Option<ClipKind> {
    if from_ahatools || types.iter().any(|t| SKIP_TYPES.contains(&t.as_str()) || t.starts_with("com.agilebits.")) {
        return None;
    }
    let has = |t: &str| types.iter().any(|x| x == t);
    if has("public.file-url") {
        Some(ClipKind::Files)
    } else if has("public.png") || has("public.tiff") || has("public.jpeg") {
        Some(ClipKind::Image)
    } else if has("public.utf8-plain-text") {
        Some(ClipKind::Text)
    } else {
        None
    }
}

fn poll() {
    autoreleasepool(|_| {
        let board = NSPasteboard::generalPasteboard();
        let count = board.changeCount();
        let mut state = STATE.lock().unwrap();
        if count == state.count {
            return;
        }
        let first = state.count < 0;
        state.count = count;
        // Whatever was on the clipboard at launch isn't a fresh copy.
        if first || count == state.own {
            state.copied = None;
            return;
        }
        let types: Vec<String> = board.types().map(|t| t.iter().map(|t| t.to_string()).collect()).unwrap_or_default();
        let front = NSWorkspace::sharedWorkspace().frontmostApplication();
        let bundle = front.as_ref().and_then(|app| app.bundleIdentifier()).map(|id| id.to_string());
        let ours = bundle.as_deref() == Some("com.ahatools.app");
        state.copied = classify(&types, ours).map(|kind| (Instant::now(), kind));
        // History keeps copies made inside AhaTools too, but never its own writes.
        if let Some(kind) = classify(&types, false) {
            let app = front.and_then(|a| a.localizedName()).map(|n| n.to_string());
            PENDING.lock().unwrap().push(Pending { count, kind, bundle, app });
        }
    });
}

pub fn start(app: AppHandle) {
    poll();
    PENDING.lock().unwrap().clear();
    thread::spawn(move || loop {
        thread::sleep(Duration::from_millis(500));
        poll();
        let pending: Vec<Pending> = std::mem::take(&mut *PENDING.lock().unwrap());
        // Only the latest can still be read; earlier ones were copied over already.
        if let Some(last) = pending.into_iter().last() {
            crate::plugins::clipboard_history::record(&app, last);
        }
    });
}

/// After AhaTools itself writes the clipboard.
pub fn mark_own() {
    let count = crate::clipboard::change_count();
    let mut state = STATE.lock().unwrap();
    state.own = count;
    if state.count == count {
        state.copied = None;
    }
}

#[tauri::command]
pub fn clipboard_mark_own() {
    mark_own();
}

#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Recent {
    /// Identifies the copy, so the panel brings each one in only once.
    pub change_count: isize,
    pub age_ms: u64,
    pub kind: ClipKind,
}

/// The last copy if it happened within `within`; looks again first, so a copy made
/// just before the hotkey isn't missed between polls.
pub fn recent(within: Duration) -> Option<Recent> {
    if within.is_zero() {
        return None;
    }
    poll();
    let state = STATE.lock().unwrap();
    let (at, kind) = state.copied?;
    let age = at.elapsed();
    (age <= within).then(|| Recent { change_count: state.count, age_ms: age.as_millis() as u64, kind })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn types(list: &[&str]) -> Vec<String> {
        list.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn kinds_follow_the_richest_type_and_skip_private_copies() {
        assert_eq!(classify(&types(&["public.file-url", "public.utf8-plain-text", "public.tiff"]), false), Some(ClipKind::Files));
        assert_eq!(classify(&types(&["public.png", "public.utf8-plain-text"]), false), Some(ClipKind::Image));
        assert_eq!(classify(&types(&["public.utf8-plain-text", "public.html"]), false), Some(ClipKind::Text));
        assert_eq!(classify(&types(&["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]), false), None);
        assert_eq!(classify(&types(&["public.utf8-plain-text", "com.agilebits.onepassword"]), false), None);
        assert_eq!(classify(&types(&["public.utf8-plain-text"]), true), None);
        assert_eq!(classify(&types(&["com.apple.custom"]), false), None);
    }
}
